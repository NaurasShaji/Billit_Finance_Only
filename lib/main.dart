import 'package:flutter/foundation.dart' show kIsWeb;
import 'package:flutter/material.dart';
import 'package:sqflite/sqflite.dart';
import 'package:sqflite_common_ffi_web/sqflite_ffi_web.dart';

import 'screens/app_shell.dart';
import 'screens/login_screen.dart';
import 'services/database_service.dart';
import 'services/admin_auth_service.dart';
import 'theme/app_theme.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();

  if (kIsWeb) {
    databaseFactory = databaseFactoryFfiWeb;
  }

  String? startupError;
  try {
    await ThemeController.instance.load();
    // Initialize SQLite before allowing access to screens that query it.
    // The web build must include sqlite3.wasm and sqflite_sw.js, generated by
    // dart run sqflite_common_ffi_web:setup.
    await DatabaseService.instance.database;
  } catch (error, stackTrace) {
    startupError = error.toString();
    debugPrint('Billit Finance startup failed: $error');
    debugPrintStack(stackTrace: stackTrace);
  }

  runApp(BillitFinanceApp(startupError: startupError));
}

class BillitFinanceApp extends StatelessWidget {
  const BillitFinanceApp({super.key, this.startupError});

  final String? startupError;

  @override
  Widget build(BuildContext context) => ListenableBuilder(
    listenable: ThemeController.instance,
    builder: (context, _) => MaterialApp(
      title: 'Billit Finance',
      debugShowCheckedModeBanner: false,
      theme: AppTheme.light,
      darkTheme: AppTheme.dark,
      themeMode: ThemeController.instance.mode,
      home: startupError == null
          ? const _AuthGate()
          : _StartupFailureScreen(error: startupError!),
    ),
  );
}

class _StartupFailureScreen extends StatelessWidget {
  const _StartupFailureScreen({required this.error});

  final String error;

  @override
  Widget build(BuildContext context) => Scaffold(
    body: Center(
      child: ConstrainedBox(
        constraints: const BoxConstraints(maxWidth: 720),
        child: Padding(
          padding: const EdgeInsets.all(24),
